"""Minimal roxygen-to-Rd converter for subsampleIRT (no roxygen2 needed).
Supports: title, description paragraphs, @param, @return, @examples, @export,
@rdname, \\method usage for S3 methods. Usage: python3 tools/roxy2rd.py .  (from the package root)"""
import re, sys, os, collections

pkg = sys.argv[1]
src = open(os.path.join(pkg, "R", "api.R")).read().split("\n")
GENERICS = {"print", "coef", "vcov", "summary"}

blocks, i = [], 0
while i < len(src):
    if src[i].startswith("#'"):
        doc = []
        while i < len(src) and src[i].startswith("#'"):
            doc.append(src[i][2:][1:] if src[i][2:3] == " " else src[i][2:]); i += 1
        sig = []
        while i < len(src) and "<- function(" not in src[i]:
            i += 1
        while i < len(src):
            sig.append(src[i]); i += 1
            s = " ".join(sig)
            body = s[s.index("function(") + 8:]
            depth = 0; end = None
            for k, ch in enumerate(body):
                depth += ch == "("; depth -= ch == ")"
                if depth == 0:
                    end = k; break
            if end is not None:
                break
        s = " ".join(x.strip() for x in sig)
        name = s.split("<-")[0].strip()
        body = s[s.index("function(") + 8:]
        depth = 0
        for k, ch in enumerate(body):
            depth += ch == "("; depth -= ch == ")"
            if depth == 0:
                args = body[1:k]; break
        blocks.append((name, args, doc))
    else:
        i += 1

def parse(doc):
    tags = collections.OrderedDict(); params = []; cur = None; free = []
    for line in doc:
        m = re.match(r"@(\w+)\s*(.*)", line)
        if m:
            t, rest = m.groups()
            if t == "param":
                pn, _, txt = rest.partition(" ")
                params.append([pn, txt]); cur = ("param", len(params) - 1)
            else:
                tags[t] = rest; cur = ("tag", t)
        elif cur is None:
            free.append(line)
        elif cur[0] == "param":
            params[cur[1]][1] += "\n" + line.strip()
        else:
            tags[cur[1]] += "\n" + line
    paras = [p.strip() for p in "\n".join(free).split("\n\n") if p.strip()]
    return paras, params, tags

def usage(name, args):
    a = re.sub(r"\s+", " ", args).strip()
    gen, _, cls = name.partition(".")
    if gen in GENERICS and cls:
        return "\\method{%s}{%s}(%s)" % (gen, cls, a)
    return "%s(%s)" % (name, a)

def wrap_usage(u):
    out, line = [], ""
    for part in re.split(r"(?<=,) ", u):
        if len(line) + len(part) > 78 and line:
            out.append(line.rstrip()); line = "  "
        line += part + " "
    out.append(line.rstrip())
    return "\n".join(out)

docs = collections.OrderedDict()
for name, args, doc in blocks:
    paras, params, tags = parse(doc)
    target = tags.get("rdname", "").strip() or name
    if target not in docs:
        docs[target] = {"names": [], "usages": [], "paras": paras, "params": [], "tags": tags}
    d = docs[target]
    d["names"].append(name); d["usages"].append(usage(name, args))
    known = {p[0] for p in d["params"]}
    d["params"] += [p for p in params if p[0] not in known]
    for k, v in tags.items():
        if k not in d["tags"]:
            d["tags"][k] = v

os.makedirs(os.path.join(pkg, "man"), exist_ok=True)
for target, d in docs.items():
    if not d["paras"]:
        continue  # undocumented (print methods)
    title, desc = d["paras"][0], d["paras"][1:]
    lines = ["%% Generated by tools/roxy2rd.py from R/api.R: do not edit by hand",
             "\\name{%s}" % target]
    for n in d["names"]:
        lines.append("\\alias{%s}" % n)
    lines += ["\\title{%s}" % title.replace("\n", " "), "\\usage{",
              "\n\n".join(wrap_usage(u) for u in d["usages"]), "}", "\\arguments{"]
    for pn, txt in d["params"]:
        lines.append("\\item{%s}{%s}" % (pn, txt.strip()))
    lines.append("}")
    lines += ["\\description{", "\n\n".join(desc) if desc else title, "}"]
    if "return" in d["tags"]:
        lines += ["\\value{", d["tags"]["return"].strip(), "}"]
    if "examples" in d["tags"]:
        lines += ["\\examples{", d["tags"]["examples"].strip("\n"), "}"]
    open(os.path.join(pkg, "man", target + ".Rd"), "w").write("\n".join(lines) + "\n")
    print("man/%s.Rd" % target)

# NAMESPACE
exports, s3 = [], []
for name, args, doc in blocks:
    if not any(l.startswith("@export") for l in doc):
        continue
    gen, _, cls = name.partition(".")
    if gen in GENERICS and cls:
        s3.append((gen, cls))
    else:
        exports.append(name)
ns = ["# Generated by tools/roxy2rd.py: do not edit by hand", ""]
ns += ["export(%s)" % e for e in exports]
ns += ["S3method(%s,%s)" % g for g in s3]
ns += ["importFrom(Matrix,sparseMatrix)",
       "importFrom(stats,optim,plogis,qlogis,qnorm,rbinom,rnorm,uniroot,setNames,vcov)"]
open(os.path.join(pkg, "NAMESPACE"), "w").write("\n".join(ns) + "\n")
print("NAMESPACE:", len(exports), "exports,", len(s3), "S3 methods")
